/** @typedef {{ cx: number, cy: number, lipY: number, radius: number }} CupGeom */

export const CUP_RADIUS = 22;

/**
 * Black air bbox inside hole overlay tile → world cup coords.
 * @param {HTMLCanvasElement} canvas
 * @param {number} px world x (tile top-left)
 * @param {number} py world y
 */
export function cupGeomFromHoleTile(canvas, px, py) {
  const w = canvas.width;
  const h = canvas.height;
  const data = canvas.getContext('2d').getImageData(0, 0, w, h).data;
  let xmin = w;
  let ymin = h;
  let xmax = -1;
  let ymax = -1;
  let sumX = 0;
  let sumY = 0;
  let n = 0;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 4;
      const r = data[i];
      const g = data[i + 1];
      const b = data[i + 2];
      if (r <= 16 && g <= 16 && b <= 16) {
        xmin = Math.min(xmin, x);
        ymin = Math.min(ymin, y);
        xmax = Math.max(xmax, x);
        ymax = Math.max(ymax, y);
        sumX += x;
        sumY += y;
        n += 1;
      }
    }
  }
  if (n === 0) {
    return {
      cx: px + w / 2,
      cy: py + h / 2,
      lipY: py + h / 2,
      radius: CUP_RADIUS,
    };
  }
  const lipY = py + ymin;
  const cx = px + sumX / n;
  const cy = lipY + CUP_RADIUS * 1.2;
  return { cx, cy, lipY, radius: CUP_RADIUS };
}

/**
 * @param {object} opts
 * @param {string} opts.mapName
 * @param {number} opts.defaultPar
 * @param {Array<{x:number,y:number}>} opts.tees
 * @param {Array<{x:number,y:number, geom: CupGeom}>} opts.cups
 */
export function buildGolfToml({ mapName, defaultPar, tees, cups }) {
  const teeSorted = [...tees].sort((a, b) => a.x - b.x);
  const cupSorted = [...cups].sort((a, b) => a.geom.cx - b.geom.cx);
  const n = Math.min(teeSorted.length, cupSorted.length);
  const lines = [
    '# Auto-generated by wkGolf map editor',
    `# ${n} hole(s) — tee + hole overlay pairs (sorted left→right)`,
    `map = "${mapName}"`,
    'hud = true',
    '',
  ];
  for (let i = 0; i < n; i++) {
    const tee = teeSorted[i];
    const cup = cupSorted[i];
    lines.push('[[holes]]');
    lines.push('origin_x = 0');
    lines.push('origin_y = 0');
    lines.push(`tee_x = ${tee.x.toFixed(1)}`);
    lines.push(`tee_y = ${tee.y.toFixed(1)}`);
    lines.push(`cup_x = ${cup.geom.cx.toFixed(1)}`);
    lines.push(`cup_y = ${cup.geom.cy.toFixed(1)}`);
    lines.push(`radius = ${Math.round(cup.geom.radius)}`);
    lines.push(`par = ${defaultPar}`);
    lines.push('');
  }
  return lines.join('\n');
}

export function downloadText(text, filename) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([text], { type: 'text/plain' }));
  a.download = filename;
  a.click();
  URL.revokeObjectURL(a.href);
}
